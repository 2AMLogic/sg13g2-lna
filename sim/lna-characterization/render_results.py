def build_rows(cells, ratified):
    nominal = cells[f"sp_{NOMINAL[0]}_{NOMINAL[1]}c_vdd{NOMINAL[2]}v"]
    rows = []
    for rid, label, rat_id, getter, unit, worst, cols, stat in ROW_DEFS:
        w, b = _sel(cells, getter, worst)
        nv, nf = getter(nominal)
        nom = {"value": nv, "point_id": nominal["point_id"]}
        if nf is not None:
            nom["freq_hz"] = nf
        row = {"id": rid, "label": label, "unit": unit, "input_columns": cols,
               "statistic": stat, "nominal": nom,
               "worst": _ext(w, cells), "best": _ext(b, cells), "tested_cells": len(cells)}
        if rid == "gain":
            row["nominal"]["band_max"] = nominal["s21_db_max"]
        if rat_id is None:
            row["classification"] = "context"
        else:
            r = ratified[rat_id]
            row["classification"] = r["classification"]
            row["limit"] = {"comparator": r["comparator"], "value": float(r["limit"]),
                            "unit": r["unit"], "status": r["status"],
                            "source": f"{RATIFIED}#{r['id']}", "spec_row": r["selector"],
                            "spec_file": SPEC}
            cmp_ = COMPARATORS[r["comparator"]]
            lim = float(r["limit"])
            fails = sorted(pid for pid in cells if not cmp_(getter(cells[pid])[0], lim))
            row["failing_cells"] = len(fails)
            row["failing_point_ids"] = fails
            if r["classification"] == "requirement":
                row["numerical_verdict"] = "pass" if not fails else "fail"
                row["coverage_status"] = "incomplete"
            elif r["classification"] == "not-ratified":
                row["advisory_only"] = True
        rows.append(row)
    mu_in = _sel(cells, lambda c: (c["mu_inband_min"], None), "min")
    k_in = _sel(cells, lambda c: (c["k_inband_min"], None), "min")
    by = {r["id"]: r for r in rows}
    by["mu"]["inband_context"] = {
        "column": "mu_inband_min", "nominal": nominal["mu_inband_min"],
        "min": _ext(mu_in[0], cells), "max": _ext(mu_in[1], cells),
        "cells_not_above_1": sum(1 for c in cells.values() if not c["mu_inband_min"] > 1)}
    by["k"]["inband_context"] = {
        "column": "k_inband_min", "nominal": nominal["k_inband_min"],
        "min": _ext(k_in[0], cells), "max": _ext(k_in[1], cells)}
    rails = sorted({c["vdd_v"] for c in cells.values()})
    sup = ratified["supply"]
    rows.append({
        "id": "supply", "label": "Supply", "classification": "context", "unit": "V",
        "input_columns": ["vdd_v"], "statistic": "unique swept rails",
        "rails": rails, "tested_cells": len(cells),
        "cells_per_rail": {f"{v:.2f}": sum(1 for c in cells.values() if c["vdd_v"] == v)
                           for v in rails},
        "limit": {"comparator": sup["comparator"], "value": float(sup["limit"]),
                  "tolerance_pct": float(sup["tolerance_pct"]), "unit": sup["unit"],
                  "status": sup["status"], "source": f"{RATIFIED}#supply",
                  "spec_row": sup["selector"], "spec_file": SPEC},
        "note": "coverage/context for the 1.80 V +/-10 % rail; not an RF performance pass"})
    order = ["gain", "nf290", "nfmin", "s11", "s22", "mu", "k", "delta", "negres_s11",
             "negres_s22", "iip3", "supply", "power", "ic1"]
    rows.sort(key=lambda r: order.index(r["id"]))
    for r in rows:
        if r["id"] == "iip3":
            r["draft_advisory"] = {"comparator": r["limit"]["comparator"],
                                   "value": r["limit"]["value"], "unit": "dBm",
                                   "cells_not_meeting": r["failing_cells"],
                                   "cells_meeting": r["tested_cells"] - r["failing_cells"]}
            r.pop("failing_cells", None)
            r.pop("failing_point_ids", None)
    return rows


# ------------------------------------------------------------- rendering

def num(v, dp):
    return f"{v:.{dp}f}".replace("-", "\u2212")


def mhz(f):
    return f"{f / 1e6:.1f} MHz"


def _t(row_id, rows):
    return next(r for r in rows if r["id"] == row_id)


def _req(r):
    lim = r["limit"]
    sym = lim["comparator"]
    return f"{sym} {num(lim['value'], 10).rstrip('0').rstrip('.')} {lim['unit']}"


def _fail(r):
    return f"fails: {r['failing_cells']}/{r['tested_cells']}"


def render_block(rows, doc):
    g = {r["id"]: r for r in rows}

    def v(r, who, dp, f=False):
        e = r[who]
        s = f"{num(e['value'], dp)}"
        if f and "freq_hz" in e:
            s += f" at {mhz(e['freq_hz'])}"
        return s

    def cell(r, who, dp, unit="", f=False):
        e = r[who]
        u = f" {unit}" if unit else ""
        return f"**{v(r, who, dp, f)}{u}** ({e['cell']})"

