# --------------------------------------------------------------------- io

def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def _read_text(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except OSError as exc:
        raise RenderError(f"unreadable: {path}: {exc}")


def _load_parser():
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "parse_lna_sweep.py")
    spec = importlib.util.spec_from_file_location("parse_lna_sweep", path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("parse_lna_sweep", mod)
    spec.loader.exec_module(mod)
    return mod


