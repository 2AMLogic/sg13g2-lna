def _cells(line):
    inner = line.strip()
    if not (inner.startswith("|") and inner.endswith("|")):
        raise RenderError("malformed spec table line")
    return [c.strip() for c in re.split(r"(?<!\\)\|", inner[1:-1])]


def normalize(text):
    t = text.replace("\\|", "|").replace("**", "").replace("`", "")
    t = t.replace("\u2212", "-")
    return re.sub(r"\s+", " ", t).strip()


def parse_spec_rows(text):
    """Rows of the authoritative '## Ratified target table': list of
    (parameter, value, binding) normalized cells."""
    lines = text.splitlines()
    try:
        start = next(i for i, l in enumerate(lines) if l.strip() == "## Ratified target table")
    except StopIteration:
        raise RenderError("spec: '## Ratified target table' heading not found")
    rows, seen = [], False
    for l in lines[start + 1:]:
        if l.startswith("|"):
            seen = True
            c = _cells(l)
            if len(c) != 5:
                raise RenderError(f"spec: ratified table row has {len(c)} cells, expected 5")
            rows.append(c)
        elif seen:
            break
    if len(rows) < 3:
        raise RenderError("spec: ratified target table not found")
    rows = rows[2:]  # header + separator
    return [(normalize(r[0]), normalize(r[1]), normalize(r[2])) for r in rows]


def load_ratified(root):
    """Validated ratified-rows.json: dict id -> entry. Each entry's
    comparator/limit/unit/status must match the spec table exactly."""
    spec_rows = parse_spec_rows(_read_text(os.path.join(root, SPEC)))
    try:
        doc = json.loads(_read_text(os.path.join(root, RATIFIED)))
    except ValueError as exc:
        raise RenderError(f"{RATIFIED}: invalid JSON: {exc}")
    entries = doc.get("rows")
    if not isinstance(entries, list) or not entries:
        raise RenderError(f"{RATIFIED}: no rows")
    out = {}
    for e in entries:
        for key in ("id", "selector", "column", "status", "comparator", "limit",
                    "unit", "template", "anchor", "classification"):
            if key not in e:
                raise RenderError(f"{RATIFIED}: entry {e.get('id')!r} missing {key!r}")
        if e["id"] in out:
            raise RenderError(f"{RATIFIED}: duplicate id {e['id']!r}")
        if e["comparator"] not in COMPARATORS and e["comparator"] != "\u00b1":
            raise RenderError(f"{RATIFIED}: {e['id']}: unknown comparator {e['comparator']!r}")
        hits = [r for r in spec_rows if r[0].startswith(e["selector"])]
        if len(hits) != 1:
            raise RenderError(
                f"{RATIFIED}: {e['id']}: selector {e['selector']!r} matches "
                f"{len(hits)} spec rows (need exactly 1)")
        param, value, binding = hits[0]
        status = "not-ratified" if "NOT RATIFIED" in param else (
            "ratified" if "RATIFIED" in param else "unmarked")
        if status != e["status"]:
            raise RenderError(
                f"{RATIFIED}: {e['id']}: status {e['status']!r} but {SPEC} row "
                f"{e['selector']!r} is {status!r}")
        cell = {"value": value, "binding": binding}.get(e["column"])
        if cell is None:
            raise RenderError(f"{RATIFIED}: {e['id']}: unknown column {e['column']!r}")
        fmt = {k: e[k] for k in ("comparator", "limit", "unit")}
        fmt["tolerance_pct"] = e.get("tolerance_pct", "")
        want = e["template"].format(**fmt)
        if e["anchor"] == "start":
            ok = cell.startswith(want)
        elif e["anchor"] == "unique":
            ok = cell.count(want) == 1
        else:
            raise RenderError(f"{RATIFIED}: {e['id']}: bad anchor {e['anchor']!r}")
        if not ok:
            raise RenderError(
                f"{RATIFIED}: {e['id']}: {SPEC} row {e['selector']!r} "
                f"({e['column']} column) does not state {want!r} "
                f"(anchor={e['anchor']})")
        out[e["id"]] = e
    return out


# ------------------------------------------------------------------ data

def expected_point_ids():
    return {f"sp_{c}_{t}c_vdd{v}v": (c, t, v)
            for c in CORNERS for t in TEMPS for v in VDDS}


def _finite(path, what, text):
    try:
        v = float(text)
    except (TypeError, ValueError):
        raise RenderError(f"{path}: {what}: malformed number {text!r}")
    if not math.isfinite(v):
        raise RenderError(f"{path}: {what}: non-finite value {text!r}")
    return v


def load_summary(path):
    text = _read_text(path)
    reader = csv.DictReader(text.splitlines())
    missing = [c for c in CSV_COLS if c not in (reader.fieldnames or [])]
    if missing:
        raise RenderError(f"{path}: missing columns {missing}")
    want = expected_point_ids()
    cells = {}
    for ln, row in enumerate(reader, 2):
        pid = row["point_id"]
        if pid in cells:
            raise RenderError(f"{path}: duplicate point_id {pid!r}")
        if pid not in want:
            raise RenderError(f"{path}: line {ln}: unexpected point_id {pid!r}")
        rec = {}
        for c in CSV_COLS:
            raw = row.get(c)
            if raw is None or raw == "":
                raise RenderError(f"{path}: {pid}: empty {c}")
            rec[c] = raw if c in TEXT_COLS else _finite(path, f"{pid}.{c}", raw)
        corner, temp, vdd = want[pid]
        if (rec["corner_label"] != corner or int(rec["temp_c"]) != int(temp)
                or abs(rec["vdd_v"] - float(vdd)) > 1e-9):
            raise RenderError(f"{path}: {pid}: corner/temp/vdd columns disagree with the point_id")
        cells[pid] = rec
    gone = sorted(set(want) - set(cells))
    if gone:
        raise RenderError(f"{path}: missing cells {gone}")
    return cells


def load_stability(path, parser):
    """Raw broadband extrema with the frequency of each: (value, f_hz)."""
    why = parser.validate_table(path, "stability", STAB_GRID)
    if why:
        raise RenderError(f"{path}: " + "; ".join(why))
    rows = []
    with open(path) as fh:
        for line in fh:
            if line.split():
                rows.append([float(x) for x in line.split()])
    if len(rows) != N_STAB_POINTS:
        raise RenderError(f"{path}: {len(rows)} frequency points, expected {N_STAB_POINTS}")

    def ext(fc, vc, pick):
        best = None
        for r in rows:  # ascending f: first occurrence wins ties
            if best is None or pick(r[vc], best[0]):
                best = (r[vc], r[fc])
        return best

    lt, gt = (lambda a, b: a < b), (lambda a, b: a > b)
    return {
        "k_min": ext(0, 1, lt), "mu_min": ext(2, 3, lt), "delta_max": ext(4, 5, gt),
        "s11_max": ext(6, 7, gt), "s22_max": ext(10, 11, gt),
    }


def load_inputs(root, record=RECORD_ID):
    parser = _load_parser()
    csv_rel = CSV_PATH.format(rec=record)
    dat_rel = DAT_DIR.format(rec=record)
    cells = load_summary(os.path.join(root, csv_rel))
    dat_dir = os.path.join(root, dat_rel)
    try:
        present = {f for f in os.listdir(dat_dir) if f.endswith(".stability.dat")}
    except OSError as exc:
        raise RenderError(f"unreadable: {dat_dir}: {exc}")
    want = {pid + ".stability.dat" for pid in cells}
    if present - want:
        raise RenderError(f"{dat_rel}: unexpected stability tables {sorted(present - want)}")
    if want - present:
        raise RenderError(f"{dat_rel}: missing stability tables {sorted(want - present)}")
    hashes = {}
    for pid in sorted(cells):
        p = os.path.join(dat_dir, pid + ".stability.dat")
        cells[pid]["raw"] = load_stability(p, parser)
        hashes[pid] = _sha256(p)
        _cross_check(pid, cells[pid])
    if "_".join(NOMINAL) and f"sp_{NOMINAL[0]}_{NOMINAL[1]}c_vdd{NOMINAL[2]}v" not in cells:
        raise RenderError("nominal cell absent")
    return cells, {"summary_csv": {"path": csv_rel, "sha256": _sha256(os.path.join(root, csv_rel))},
                   "stability_tables": {pid: {"path": f"{dat_rel}/{pid}.stability.dat",
                                              "sha256": h} for pid, h in hashes.items()}}


def _cross_check(pid, c):
    raw = c["raw"]
    pairs = (("k_broadband_min", raw["k_min"][0]), ("mu_broadband_min", raw["mu_min"][0]),
             ("mag_delta_broadband_max", raw["delta_max"][0]),
             ("s11_mag_broadband_max", raw["s11_max"][0]),
             ("s22_mag_broadband_max", raw["s22_max"][0]))
    for col, rv in pairs:
        if abs(c[col] - rv) > CROSS_TOL:
            raise RenderError(
                f"{pid}: summary {col}={c[col]} disagrees with the raw stability table ({rv}); "
                "stale or mismatched inputs")
    nf = max(c["nf290_db_at_band_lo"], c["nf290_db_at_band_mid"], c["nf290_db_at_band_hi"])
    if abs(c["nf290_db_worst"] - nf) > NF_TOL:
        raise RenderError(f"{pid}: nf290_db_worst disagrees with its three sampled frequencies")


