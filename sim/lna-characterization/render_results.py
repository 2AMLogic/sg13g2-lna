def _label(c):
    return f"{c['corner_label']}/{num(int(c['temp_c']), 0)} \u00b0C/{c['vdd_v']:.2f} V"


def _sel(cells, getter, worst):
    """(worst, best) over cells by (value) with ties broken by smallest
    point_id (iteration in sorted order, strict improvement only)."""
    lo_is_worst = worst == "min"
    w = b = None
    for pid in sorted(cells):
        v, f = getter(cells[pid])
        entry = (v, pid, f)
        if w is None or (v < w[0] if lo_is_worst else v > w[0]):
            w = entry
        if b is None or (v > b[0] if lo_is_worst else v < b[0]):
            b = entry
    return w, b


def _ext(entry, cells):
    v, pid, f = entry
    d = {"value": v, "point_id": pid, "cell": _label(cells[pid])}
    if f is not None:
        d["freq_hz"] = f
    return d


