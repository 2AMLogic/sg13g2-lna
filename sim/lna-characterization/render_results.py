def build_doc(root):
    ratified = load_ratified(root)
    cells, inputs = load_inputs(root)
    rows = build_rows(cells, ratified)
    inputs["ratified_rows"] = {"path": RATIFIED, "sha256": _sha256(os.path.join(root, RATIFIED))}
    doc = {
        "schema": "results-verdicts/1",
        "record_id": RECORD_ID,
        "nominal_cell": f"sp_{NOMINAL[0]}_{NOMINAL[1]}c_vdd{NOMINAL[2]}v",
        "grid": {"corners": sorted(CORNERS), "temps_c": [int(t) for t in sorted(TEMPS, key=int)],
                 "vdd_v": [float(v) for v in VDDS], "cells": len(cells),
                 "stability_grid": dict(STAB_GRID, points=N_STAB_POINTS)},
        "inputs": inputs,
        "temperature_references": {
            "nf290_db_worst": "T0 = 290 K (requirement)",
            "nfmin_sp_db_at_band_lo": "analysis temperature (context; not relabeled as 290 K)"},
        "sampling": {"nf290": "three frequencies: band low, mid, high",
                     "stability": "140 points, 40 pts/decade, 10 MHz to 29.85 GHz",
                     "inband": "in-band S-parameter grid of the summary CSV"},
        "coverage": {"status": "incomplete", "limitations": LIMITATIONS},
        "claims": "numerical verdicts on a historical record only; no full-spec compliance, "
                  "no T1 signoff, no spec ratification",
        "rows": rows,
    }
    return doc


def dump_json(doc):
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def splice(readme, block):
    i, j = readme.find(BEGIN), readme.find(END)
    if i < 0 or j < 0 or j < i or readme.count(BEGIN) != 1 or readme.count(END) != 1:
        raise RenderError(f"{README}: need exactly one results-table begin/end marker pair")
    return readme[:i] + BEGIN + "\n\n" + block + "\n" + readme[j:]


def current_block(readme):
    i, j = readme.find(BEGIN), readme.find(END)
    if i < 0 or j < i:
        raise RenderError(f"{README}: results-table markers missing")
    return readme[i + len(BEGIN):j].strip("\n") + "\n"


# ------------------------------------------- derived 290 K noise-floor prose
# Issue #187: the current reachability narrative in the README is generated
# from the committed derived view (views/<rec>-nfmin290.csv, band-low sample at
# 2.4 GHz, NFmin re-referenced to T0 = 290 K), so it cannot drift from it.

NARR_NAMES = ("nfmin290-summary", "nfmin290-inline")


def _narr_markers(name):
    return (f"<!-- {name}:begin (generated by sim/lna-characterization/"
            f"render_results.py --update-narrative; do not edit by hand) -->",
            f"<!-- {name}:end -->")


def load_nfmin290(root):
    nf_row = load_ratified(root).get("nf")
    if not nf_row or float(nf_row["limit"]) != NF_TARGET_DB or nf_row["comparator"] != "<":
        raise RenderError(f"{RATIFIED}: nf row is no longer '< {NF_TARGET_DB}'; update NF_TARGET_DB")
    path = os.path.join(root, NF290_VIEW.format(rec=RECORD_ID))
    with open(path, encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    if len(rows) != 45:
        raise RenderError(f"{path}: expected 45 cells, found {len(rows)}")
    nom_id = f"sp_{NOMINAL[0]}_{NOMINAL[1]}c_vdd{NOMINAL[2]}v"
    for r in rows:
        if r["source_record_id"] != RECORD_ID:
            raise RenderError(f"{path}: {r['point_id']}: wrong source record")
        if float(r["nfmin290_t_ref_k"]) != 290.0:
            raise RenderError(f"{path}: {r['point_id']}: not referenced to 290 K")
        if abs(float(r["freq_hz"]) - 2.4e9) > 1:
            raise RenderError(f"{path}: {r['point_id']}: not the band-low sample")
        gap = float(r["nf290_db_at_band_lo"]) - float(r["nfmin290_db_at_band_lo"])
        if abs(gap - float(r["nf290_minus_nfmin290_db_at_band_lo"])) > NF_TOL:
            raise RenderError(f"{path}: {r['point_id']}: gap column inconsistent")
    def lbl(r):
        return f"{r['corner_label']}/{r['temp_c'].replace('-', chr(0x2212))} \u00b0C/{float(r['vdd_v']):.2f} V"
    key = lambda r: float(r["nfmin290_db_at_band_lo"])
    best, worst = min(rows, key=key), max(rows, key=key)
    nom = [r for r in rows if r["point_id"] == nom_id]
    if len(nom) != 1:
        raise RenderError(f"{path}: nominal cell {nom_id} missing")
    nom = nom[0]
    return {
        "best": (key(best), lbl(best)), "worst": (key(worst), lbl(worst)),
        "nominal": (key(nom), lbl(nom)),
        "nominal_nf290": float(nom["nf290_db_at_band_lo"]),
        "nominal_gap": float(nom["nf290_minus_nfmin290_db_at_band_lo"]),
        "nominal_raw": float(nom["nfmin_sp_db_at_band_lo"]),
        "below_target": sum(1 for r in rows if key(r) < NF_TARGET_DB),
        "cells": len(rows),
    }


