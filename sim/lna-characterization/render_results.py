"""Deterministic renderer for the measurements results table (issue #141).

Reads ONE explicitly selected historical record (RECORD_ID below -- never
chosen by filesystem order or newest timestamp): its summary CSV and the 45
raw broadband ``*.stability.dat`` tables. Emits

  * the fenced Markdown table block inside ``measurements/README.md``
    (between the ``results-table:begin/end`` markers), and
  * ``measurements/results-verdicts.json`` (numerical verdicts, context rows,
    DRAFT/unratified rows, coverage limitations, input hashes).

Limits and ratification statuses come from ``spec/ratified-rows.json``, which
is itself validated against the value/definition column of the authoritative
table in ``spec/target-spec.md`` (a mutated comparator, limit, unit, status,
or a missing/duplicate row is an error).

Modes (exactly one):
  --check                 read-only drift check of the committed block + JSON
  --update                deliberately rewrite the README block and the JSON
  --out-md P --out-json Q write scratch copies (block text / JSON) only

Nothing here claims full-spec compliance or signoff: the record is historical
and covers neither the L/C-mismatch axis nor matching networks, and NF is
sampled at three frequencies. Missing or corrupt inputs are errors.

Stdlib only; run as ``python3 -I sim/lna-characterization/render_results.py``.
"""
