def _splice_one(text, name, body):
    b, e = _narr_markers(name)
    if text.count(b) != 1 or text.count(e) != 1 or text.find(e) < text.find(b):
        raise RenderError(f"{README}: need exactly one {name} begin/end marker pair")
    i, j = text.find(b), text.find(e)
    sep = "\n\n" if name == "nfmin290-summary" else ""
    return text[:i] + b + sep + body + sep + text[j:]


def splice_narrative(text, blocks):
    for name in NARR_NAMES:
        text = _splice_one(text, name, blocks[name])
    return text


def check_narrative(root):
    """Return a list of drift messages (empty if the README's current
    reachability prose matches the derived 290 K view)."""
    text = _read_text(os.path.join(root, README))
    blocks = render_narrative(load_nfmin290(root))
    try:
        fresh = splice_narrative(text, blocks)
    except RenderError as exc:
        return [str(exc)]
    if fresh != text:
        return [f"{README}: 290 K noise-floor summary is stale or hand-edited "
                f"(source: {NF290_VIEW.format(rec=RECORD_ID)})"]
    return []


# ------------------------------------------------------------------- cli

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=os.path.abspath(
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")))
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="read-only drift check")
    mode.add_argument("--update", action="store_true", help="rewrite README block + JSON")
    mode.add_argument("--check-narrative", action="store_true",
                      help="read-only check of the 290 K noise-floor prose (PDK-free)")
    mode.add_argument("--update-narrative", action="store_true",
                      help="rewrite only the generated 290 K prose blocks")
    mode.add_argument("--out-md", help="write the generated block to this scratch path")
    ap.add_argument("--out-json", help="with --out-md: scratch path for the JSON")
    a = ap.parse_args(argv)
    try:
        if a.check_narrative or a.update_narrative:
            if a.check_narrative:
                bad = check_narrative(a.root)
                for b in bad:
                    print("DRIFT: " + b, file=sys.stderr)
                if bad:
                    print("regenerate with: python3 -I sim/lna-characterization/"
                          "render_results.py --update-narrative", file=sys.stderr)
                    return 1
                print("290 K noise-floor narrative is fresh")
                return 0
            rp = os.path.join(a.root, README)
            new = splice_narrative(_read_text(rp), render_narrative(load_nfmin290(a.root)))
            with open(rp, "w", encoding="utf-8") as fh:
                fh.write(new)
            return 0
        doc = build_doc(a.root)
        block = render_block(doc["rows"], doc)
        js = dump_json(doc)
        readme_path = os.path.join(a.root, README)
        json_path = os.path.join(a.root, VERDICTS)
        if a.check:
            bad = []
            if current_block(_read_text(readme_path)).strip() != block.strip():
                bad.append(f"{README}: results table block is stale or hand-edited")
            if _read_text(json_path) != js:
                bad.append(f"{VERDICTS}: stale or hand-edited")
            for b in bad:
                print("DRIFT: " + b, file=sys.stderr)
            if bad:
                print("regenerate with: python3 -I sim/lna-characterization/render_results.py --update",
                      file=sys.stderr)
                return 1
            print("results table and verdict JSON are fresh")
            return 0
        if a.update:
            new_readme = splice(_read_text(readme_path), block)
            with open(readme_path, "w", encoding="utf-8") as fh:
                fh.write(new_readme)
            with open(json_path, "w", encoding="utf-8") as fh:
                fh.write(js)
            return 0
        if not a.out_json:
            ap.error("--out-md requires --out-json")
        with open(a.out_md, "w", encoding="utf-8") as fh:
            fh.write(block)
        with open(a.out_json, "w", encoding="utf-8") as fh:
            fh.write(js)
        return 0
    except RenderError as exc:
        print(f"render_results.py: ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
